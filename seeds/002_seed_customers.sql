    SELECT so_thu_tu
    FROM generate_series(1, 1000) AS du_lieu(so_thu_tu)
), du_lieu AS (
    SELECT
        'Khách hàng tự sinh ' || LPAD(so_thu_tu::TEXT, 4, '0') AS full_name,
        '090399' || LPAD(so_thu_tu::TEXT, 4, '0') AS phone,
