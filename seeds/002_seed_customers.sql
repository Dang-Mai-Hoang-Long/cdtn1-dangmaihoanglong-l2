        'Ninh Kiều, Cần Thơ'::VARCHAR AS address,
        'MOI'::VARCHAR AS segment
    FROM mau
)
INSERT INTO customer (full_name, phone, email, address, segment)
SELECT full_name, phone, email, address, segment
FROM du_lieu
ORDER BY phone
ON CONFLICT (phone) DO NOTHING;
